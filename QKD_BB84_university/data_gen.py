"""
QKD telemetry generated by a realistic BB84 link (bb84.py) instead of hand-picked
random distributions.

Every timestep, Alice sends TIMESTEP_PULSES pulses (1 ms at 1 GHz) through the
simulated fibre to Bob. Bob's monitoring software logs what it can measure
(error rates, detection rates, dark/vacuum clicks, check-slot clicks, double clicks,
detector balance, click timing) and Alice logs her monitor photodiode. Eavesdropping
episodes switch a real attack on and off inside the simulation:

  intercept_resend, breidbart, pns, blinding, timeshift, trojan

Each episode has an intensity (the fraction of pulses Eve attacks) and is either
stealthy (Eve hides every signature she can: matches Bob's detection rate, fakes
dark counts, mimics the error rate, keeps her timing tight) or naive.
"""
import os
import json
import hashlib
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from bb84 import BB84Link

# -----------------------------------
# quick mode: set the environment variable QKD_QUICK=1 for a short test run
# (fewer timesteps, fewer datasets, fewer epochs). Results are not for the write-up.
# -----------------------------------
QUICK = os.environ.get("QKD_QUICK", "0") == "1"

# -----------------------------------
# telemetry data parameters
# -----------------------------------
TOTAL_TIMESTAMPS = 3000 if QUICK else 10000
TIMESTEP_PULSES = 1_000_000     # pulses per timestep (1 ms at 1 GHz)

# the BB84 link (anything in BB84Link.DEFAULTS can be set here)
LINK_SETTINGS = dict(
    distance_km=50.0,
    drift_sd=0.01,              # polarization drift per timestep (radians)
    drift_pull=0.01,            # slow active compensation
)

# episode generation parameters (same scheme as before)
MIN_GAP = 120
MIN_DURATION = 60
MAX_DURATION = 200
N_EPISODES = 24
STEALTH_PROB = 0.4
INTENSITY_RANGE = (0.05, 1.0)   # fraction of pulses Eve attacks

# which attacks appear, and how often
ATTACK_TYPES = {
    "intercept_resend": 1.0,
    "breidbart": 1.0,
    "pns": 1.0,
    "blinding": 1.0,
    "timeshift": 1.0,
    "trojan": 1.0,
}

# -----------------------------------
# features the detectors are trained on
# -----------------------------------
ALL_FEATURES = list(BB84Link.TELEMETRY_FEATURES)
# the original three telemetry channels, now measured on the BB84 link:
#   qber -> qber_z, jitter -> timing_jitter_ps, dark_counts -> vacuum_clicks
CLASSIC_FEATURES = ["qber_z", "timing_jitter_ps", "vacuum_clicks"]

FEATURE_SET = "all"             # "all" (11 channels) or "classic" (3 channels)
FEATURES = ALL_FEATURES if FEATURE_SET == "all" else CLASSIC_FEATURES

DATA_DIR = "data"
# the single dataset used by main.py, baseline.py, seed_sweep.py and h2_seedSweep.py
MAIN_SEED = 42
MAIN_CSV = os.path.join(DATA_DIR, "qkd_simulated_telemetry_quick.csv" if QUICK
                        else "qkd_simulated_telemetry.csv")


# -----------------------------------
# episodes
# -----------------------------------
def make_episodes(rng, total_timestamps):
    episodes = []
    cursor = int(rng.integers(200, 500))  # first attack window between these
    types = list(ATTACK_TYPES)
    weights = np.array([ATTACK_TYPES[t] for t in types], dtype=float)
    weights /= weights.sum()
    for _ in range(N_EPISODES):
        duration = int(rng.integers(MIN_DURATION, MAX_DURATION))  # how long the attack lasts
        start = cursor
        end = start + duration
        if end >= total_timestamps - 200:
            break  # stops if at the end of the dataset
        episodes.append({
            "start": start, "end": end,
            "attack": str(rng.choice(types, p=weights)),
            "intensity": float(rng.uniform(*INTENSITY_RANGE)),
            "stealthy": bool(rng.random() < STEALTH_PROB),
        })
        cursor = end + int(rng.integers(MIN_GAP, MIN_GAP * 3))  # random gap before next
    return episodes


# -----------------------------------
# telemetry data generation
# -----------------------------------
def generate_telemetry_dataset(seed, total_timestamps=TOTAL_TIMESTAMPS, verbose=False):
    """Run the BB84 link for total_timestamps timesteps and log its telemetry."""
    rng = np.random.default_rng(seed)
    episodes = make_episodes(rng, total_timestamps)
    link = BB84Link(seed=seed, **LINK_SETTINGS)

    # per-timestep schedule of what Eve is doing
    attack = np.array(["none"] * total_timestamps, dtype=object)
    intensity = np.zeros(total_timestamps)
    stealthy = np.zeros(total_timestamps, dtype=bool)
    for eps in episodes:
        s, e = eps["start"], eps["end"]
        attack[s:e] = eps["attack"]
        intensity[s:e] = eps["intensity"]
        stealthy[s:e] = eps["stealthy"]

    rows = []
    for t in range(total_timestamps):
        if attack[t] == "none":
            link.eve_active = False
        else:
            link.eve_active = True
            link.eve_attack = attack[t]
            link.eve_fraction = intensity[t]
            link.eve_stealth = bool(stealthy[t])
        feats, truth = link.telemetry_step(TIMESTEP_PULSES)
        rows.append({**feats, **truth})
        if verbose and (t + 1) % 1000 == 0:
            print(f"  seed {seed}: {t + 1}/{total_timestamps} timesteps")

    df = pd.DataFrame(rows)
    df[ALL_FEATURES] = df[ALL_FEATURES].ffill().fillna(0.0)   # empty bins (very rare)
    df.insert(0, "timestamp", np.arange(total_timestamps))
    df["attack_label"] = (attack != "none").astype(int)
    df["attack_type"] = attack
    df["attack_intensity"] = intensity
    df["is_stealthy"] = stealthy
    return df


# -----------------------------------
# caching (datasets take ~1 minute each to simulate)
# -----------------------------------
def _settings_tag(total_timestamps):
    settings = dict(T=total_timestamps, pulses=TIMESTEP_PULSES, link=LINK_SETTINGS,
                    gap=MIN_GAP, dur=(MIN_DURATION, MAX_DURATION), n=N_EPISODES,
                    stealth=STEALTH_PROB, inten=INTENSITY_RANGE, types=ATTACK_TYPES,
                    version=1)
    return hashlib.md5(json.dumps(settings, sort_keys=True).encode()).hexdigest()[:8]


def dataset_path(seed, total_timestamps=TOTAL_TIMESTAMPS):
    return os.path.join(DATA_DIR, f"bb84_telemetry_seed{seed}_{_settings_tag(total_timestamps)}.csv")


def load_or_generate(seed, total_timestamps=TOTAL_TIMESTAMPS, verbose=True):
    """Load a cached dataset, or simulate it and cache it. Changing any setting above
    gives a new file name, so stale data is never reused."""
    path = dataset_path(seed, total_timestamps)
    if os.path.exists(path):
        return pd.read_csv(path)
    if verbose:
        print(f"Simulating BB84 telemetry for seed {seed} ...", flush=True)
    df = generate_telemetry_dataset(seed, total_timestamps)
    os.makedirs(DATA_DIR, exist_ok=True)
    df.to_csv(path, index=False)
    return df


def generate_many(seeds, total_timestamps=TOTAL_TIMESTAMPS, n_jobs=None):
    """Load or simulate several datasets, simulating missing ones in parallel."""
    missing = [s for s in seeds if not os.path.exists(dataset_path(s, total_timestamps))]
    if missing:
        n_jobs = n_jobs or max(1, min(len(missing), (os.cpu_count() or 2) - 1))
        print(f"Simulating {len(missing)} BB84 telemetry datasets on {n_jobs} processes ...",
              flush=True)
        if n_jobs > 1:
            with ProcessPoolExecutor(max_workers=n_jobs) as pool:
                list(pool.map(load_or_generate, missing, [total_timestamps] * len(missing)))
        else:
            for s in missing:
                load_or_generate(s, total_timestamps)
    return [load_or_generate(s, total_timestamps, verbose=False) for s in seeds]


# -----------------------------------
# sanity-check plot
# -----------------------------------
ATTACK_COLOURS = {"intercept_resend": "#eb6834", "breidbart": "#1baf7a", "pns": "#eda100",
                  "blinding": "#e87ba4", "timeshift": "#008300", "trojan": "#6250d6"}
PLOT_LABELS = {
    "qber_z": "QBER\n(key basis)", "qber_x": "QBER\n(test basis)",
    "rate_signal": "Signal det.\n/1000 pulses", "rate_decoy": "Decoy det.\n/1000 pulses",
    "vacuum_clicks": "Vacuum\nclicks", "check_clicks": "Check-slot\nclicks",
    "double_click_frac": "Double\nclicks", "det1_frac": "Detector-1\nshare",
    "timing_offset_ps": "Timing\noffset (ps)", "timing_jitter_ps": "Timing\njitter (ps)",
    "watchdog_counts": "Alice\nwatchdog",
}


def plot_sanity_check(df, out_path="plots/telemetry_sanity_check.png", features=ALL_FEATURES):
    fig, axes = plt.subplots(len(features), 1, figsize=(14, 1.35 * len(features) + 1.2),
                             sharex=True)
    # find episodes for shading
    lab = df["attack_label"].to_numpy()
    edges = np.flatnonzero(np.diff(np.r_[0, lab, 0]))
    spans = list(zip(edges[::2], edges[1::2]))
    for ax, f in zip(axes, features):
        y = df[f].to_numpy(dtype=float)
        lo, hi = np.nanpercentile(y, [0.5, 99.5])
        pad = 0.15 * (hi - lo if hi > lo else 1)
        for s, e in spans:
            a = df["attack_type"].iloc[s]
            ax.axvspan(s, e, color=ATTACK_COLOURS.get(a, "#c3c2b7"),
                       alpha=0.12 if df["is_stealthy"].iloc[s] else 0.3, lw=0)
        ax.plot(df["timestamp"], y, color="#2a2a28", lw=0.5)
        ax.set_ylim(lo - pad, hi + pad)
        ax.set_ylabel(PLOT_LABELS.get(f, f), fontsize=8, rotation=0, ha="right", va="center")
        ax.tick_params(labelsize=7)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    axes[-1].set_xlabel("Timestep (1 ms of pulses each)")
    handles = [plt.Rectangle((0, 0), 1, 1, color=c, alpha=0.4, label=a)
               for a, c in ATTACK_COLOURS.items()]
    handles.append(plt.Rectangle((0, 0), 1, 1, color="#898781", alpha=0.15,
                                 label="(lighter = stealthy)"))
    fig.legend(handles=handles, loc="upper center", ncol=7, frameon=False, fontsize=8,
               bbox_to_anchor=(0.5, 0.995))
    fig.suptitle("BB84 link telemetry with eavesdropping episodes (shaded)", y=1.02,
                 fontsize=12)
    fig.tight_layout()
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    # simulate, save data and figures
    df = load_or_generate(seed=MAIN_SEED)
    df.to_csv(MAIN_CSV, index=False)   # the file the other scripts read

    plot_sanity_check(df)
    print(f"Saved {MAIN_CSV} and plots/telemetry_sanity_check.png")

    # quick summary of how each attack shifts each feature (relative to no attack)
    normal = df[df.attack_label == 0][ALL_FEATURES]
    mu, sd = normal.mean(), normal.std().replace(0, 1)
    print("\nAverage shift of each feature during attacks (in standard deviations of normal):")
    shift = (df[df.attack_label == 1].groupby(["attack_type", "is_stealthy"])[ALL_FEATURES]
             .mean().sub(mu).div(sd))
    with pd.option_context("display.width", 200, "display.max_columns", 20,
                           "display.float_format", "{:+.1f}".format):
        print(shift)
